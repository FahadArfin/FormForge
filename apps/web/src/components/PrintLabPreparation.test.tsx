// @vitest-environment jsdom
import {act} from 'react'
import {createRoot} from 'react-dom/client'
import {afterEach,beforeEach,expect,it,vi} from 'vitest'
import {createDocument,createNode} from '@formforge/model'
import {useEditor} from '@/store/editor'
import {PrintLabPreparation} from './PrintLabPreparation'
let host:HTMLDivElement,root:ReturnType<typeof createRoot>
beforeEach(async()=>{
 Object.assign(globalThis,{IS_REACT_ACT_ENVIRONMENT:true});vi.useFakeTimers()
 const doc={...createDocument(),nodes:[createNode('box')]}
 useEditor.setState({document:doc,mesh:null,meshDocument:null,geometryStatus:'idle',buildMode:'manual',undoStack:[],redoStack:[]})
 host=document.createElement('div');document.body.append(host);root=createRoot(host)
 await act(async()=>root.render(<PrintLabPreparation/>))
})
afterEach(async()=>{await act(async()=>root.unmount());host.remove();vi.clearAllTimers();vi.useRealTimers()})
const button=(text:string)=>[...host.querySelectorAll('button')].find(b=>b.textContent===text)!
async function upload(){
 const file=new File(['; generated by OrcaSlicer 2.3.0\n; total filament weight [g] : 10\n; total estimated time: 12m'],'part.gcode')
 Object.defineProperty(file,'arrayBuffer',{value:async()=>new TextEncoder().encode(await '; generated by OrcaSlicer 2.3.0\n; total filament weight [g] : 10\n; total estimated time: 12m').buffer})
 const input=host.querySelector<HTMLInputElement>('input[type="file"]')!;Object.defineProperty(input,'files',{value:[file]})
 await act(async()=>input.dispatchEvent(new Event('change',{bubbles:true})))
}
it('requires explicit job confirmation after preview and saves reported provenance',async()=>{
 await upload()
 expect(useEditor.getState().document.slicerResult).toBeUndefined()
 expect(button('Associate with this print job').disabled).toBe(true)
 expect(host.textContent).toContain('12 min')
 await act(async()=>host.querySelector<HTMLInputElement>('[aria-label="Confirm slicer job association"]')!.click())
 await act(async()=>button('Associate with this print job').click())
 expect(useEditor.getState().document.slicerResult).toMatchObject({slicer:'OrcaSlicer',filamentGrams:10,durationSeconds:720,association:'user-confirmed'})
 expect(host.textContent).toContain('Unknown — enter your material price')
})
it('invalidates pending confirmation and saved results when the print job changes',async()=>{
 await upload();await act(async()=>host.querySelector<HTMLInputElement>('[aria-label="Confirm slicer job association"]')!.click())
 const doc=useEditor.getState().document
 await act(async()=>useEditor.setState({document:{...doc,printer:{...doc.printer,nozzleDiameter:.6}}}))
 expect(button('Associate with this print job').disabled).toBe(true)
 expect(host.textContent).toContain('Import again')
})
it('applies printer and material presets without inventing a price',async()=>{
 await act(async()=>button('Apply printer preset').click())
 expect(useEditor.getState().document.printer).toMatchObject({name:'Bambu Lab P1S',buildVolume:{x:256,y:256,z:256},usableBedExclusions:[{x:0,y:0,width:18,depth:28}]})
 const select=host.querySelector<HTMLSelectElement>('[aria-label="PrintLab material preset"]')!
 await act(async()=>{select.value='PETG';select.dispatchEvent(new Event('change',{bubbles:true}))})
 await act(async()=>button('Apply material preset').click())
 expect(useEditor.getState().document.printMaterial).toMatchObject({name:'PETG',priceConfigured:false})
})
