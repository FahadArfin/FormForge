export type SlicerResult = NonNullable<ModelDocument['slicerResult']>
export type SlicerCandidate = Omit<SlicerResult,'jobFingerprint'|'association'>
export const slicerImportLimits = {maxInputBytes:32*1024*1024,maxEntryBytes:32*1024*1024,maxExpandedBytes:64*1024*1024,maxEntries:128}
type ImportLimits = typeof slicerImportLimits

function duration(value:string):number|undefined {
  if(!/^(?:\d+(?:\.\d+)?\s*[dhms]\s*)+$/i.test(value))return
  const factors:Record<string,number>={d:86400,h:3600,m:60,s:1}, seen=new Set<string>()
  let seconds=0
  for(const match of value.matchAll(/(\d+(?:\.\d+)?)\s*([dhms])/gi)){
    const unit=match[2]!.toLowerCase();if(seen.has(unit))return;seen.add(unit);seconds+=Number(match[1])*factors[unit]!
  }
  return Number.isFinite(seconds)&&seconds<=31_536_000?seconds:undefined
}
function mass(value:string):number|undefined {
  if(!/^\d+(?:\.\d+)?(?:\s*,\s*\d+(?:\.\d+)?)*$/.test(value))return
  const grams=value.split(',').reduce((sum,item)=>sum+Number(item.trim()),0)
  return Number.isFinite(grams)&&grams<=100_000?Number(grams.toFixed(6)):undefined
}
function unique(values:{value:number|undefined;source:string}[]){
  if(!values.length||values.some(v=>v.value===undefined)||values.some(v=>v.value!==values[0]!.value))return undefined
  return values[0]
}
/** Read only emitted comment metadata. No toolpath execution, timing simulation, or price import. */
export function parseSlicerText(text:string,fileName:string,plate?:string):SlicerCandidate {
  if(text.length>slicerImportLimits.maxEntryBytes||text.includes('\0'))throw new Error('Import a bounded text G-code file; binary G-code is not supported.')
  const result:SlicerCandidate={version:1,fileName:fileName.slice(0,256),importedAt:new Date().toISOString(),slicer:'unknown',...(plate?{plate:plate.slice(0,256)}:{})}
  const times:{value:number|undefined;source:string}[]=[],totals:{value:number|undefined;source:string}[]=[],masses:{value:number|undefined;source:string}[]=[]
  let slicerIdentity:string|undefined,identityConflict=false
  // G-code may be long; iterate lines without allocating a full array of all toolpath commands.
  const lines=/[^\r\n]+/g
  for(const found of text.matchAll(lines)){
    const line=found[0];if(line.length>4096||!/^\s*;/.test(line))continue
    const producer=line.match(/^\s*;\s*(?:generated by\s+)?(BambuStudio|OrcaSlicer|PrusaSlicer)(?:\s+([^\s;]+))?/i)
    if(producer){
      const canonical=['BambuStudio','OrcaSlicer','PrusaSlicer'].find(n=>n.toLowerCase()===producer[1]!.toLowerCase())! as SlicerResult['slicer']
      const reportedVersion=producer[2]&&/^v?\d+(?:\.\d+)+[a-z0-9.+_-]*$/i.test(producer[2])?producer[2].slice(0,80):undefined
      const identity=canonical+' '+(reportedVersion??''); if(slicerIdentity&&identity!==slicerIdentity)identityConflict=true;slicerIdentity=identity
      result.slicer=canonical;result.slicerVersion=reportedVersion
    }
    const time=line.match(/;\s*(total estimated time|estimated printing time \(normal mode\))\s*[:=]\s*([^;]+)/i)
    if(time)times.push({value:duration(time[2]!.trim()),source:`${plate??fileName}: ${time[1]}`.slice(0,512)})
    const grams=line.match(/^\s*;\s*((?:total )?filament (?:used|weight) \[g\])\s*[:=]\s*(.*?)\s*$/i)
    if(grams){const target=/^total /i.test(grams[1]!)?totals:masses;target.push({value:mass(grams[2]!),source:`${plate??fileName}: ${grams[1]}`.slice(0,512)})}
  }
  if(identityConflict){result.slicer='unknown';delete result.slicerVersion}
  const time=unique(times),grams=unique(totals.length?totals:masses)
  if(time){result.durationSeconds=time.value;result.durationSource=time.source}
  if(grams){result.filamentGrams=grams.value;result.massSource=grams.source}
  return result
}
function textBytes(bytes:Uint8Array){
  try {const text=new TextDecoder('utf-8',{fatal:true}).decode(bytes);if(text.includes('\0'))throw new Error();return text}
  catch {throw new Error('Import text G-code (UTF-8). Binary G-code is not supported.')}
}
/** Stream ZIP members in small compressed chunks; never call unzipSync on user archives. */
export function importSlicerBytes(bytes:Uint8Array,fileName:string,overrides:Partial<ImportLimits>={}):SlicerCandidate[]{
  const limits={...slicerImportLimits,...overrides}
  if(bytes.byteLength>limits.maxInputBytes)throw new Error('Slicer file exceeds the 32 MB import limit.')
  if(/\.gcode$/i.test(fileName)){
    if(bytes.length>limits.maxEntryBytes||bytes.length>limits.maxExpandedBytes)throw new Error('G-code exceeds the text size limit.')
    return [parseSlicerText(textBytes(bytes),fileName)]
  }
  if(!/\.(?:zip|3mf)$/i.test(fileName))throw new Error('Choose text .gcode or a sliced .gcode.3mf/.zip archive.')
  if(bytes[0]!==80||bytes[1]!==75)throw new Error('This is not a valid sliced ZIP archive.')
  // fflate's stream validates members, but does not require the ZIP end directory.
  const view=new DataView(bytes.buffer,bytes.byteOffset,bytes.byteLength)
  let end=-1
  for(let i=bytes.length-22;i>=Math.max(0,bytes.length-65557);i--){
    if(view.getUint32(i,true)===0x06054b50&&i+22+view.getUint16(i+20,true)===bytes.length){end=i;break}
  }
  if(end<0)throw new Error('Incomplete sliced archive; ZIP directory is missing.')
  const declaredEntries=view.getUint16(end+10,true),directorySize=view.getUint32(end+12,true),directoryOffset=view.getUint32(end+16,true)
  if(view.getUint16(end+4,true)||view.getUint16(end+6,true)||declaredEntries===65535||directoryOffset+directorySize!==end)throw new Error('Unsupported or invalid sliced archive directory.')
  if(declaredEntries>limits.maxEntries)throw new Error('Archive entry limit exceeded.')
  let entries=0,expanded=0,active=0
  const results:SlicerCandidate[]=[],names=new Set<string>()
  const unzip=new Unzip(file=>{
    if(++entries>limits.maxEntries)throw new Error('Archive entry limit exceeded.')
    if(file.name.length>256||names.has(file.name))throw new Error('Archive contains an ambiguous or oversized entry name.')
    names.add(file.name)
    if(!/\.gcode$/i.test(file.name))return // Geometry, thumbnails and executable payloads are never expanded.
    if((file.originalSize??0)>limits.maxEntryBytes||(file.originalSize??0)+expanded>limits.maxExpandedBytes)throw new Error('Archive decompression limit exceeded.')
    let size=0;const chunks:Uint8Array[]=[];active++
    file.ondata=(error,chunk,final)=>{
      if(error)throw error
      size+=chunk.length;expanded+=chunk.length
      if(size>limits.maxEntryBytes||expanded>limits.maxExpandedBytes){file.terminate();throw new Error('Archive decompression limit exceeded.')}
      chunks.push(chunk)
      if(final){const content=new Uint8Array(size);let offset=0;for(const part of chunks){content.set(part,offset);offset+=part.length}results.push(parseSlicerText(textBytes(content),fileName,file.name));active--}
    }
    file.start()
  })
  unzip.register(UnzipInflate)
  // 1 KiB input chunks bound overshoot before each output-size check, including forged size headers.
  for(let offset=0;offset<bytes.length;offset+=1024)unzip.push(bytes.subarray(offset,offset+1024),offset+1024>=bytes.length)
  if(active||entries!==declaredEntries)throw new Error('Incomplete sliced archive; export it again from your slicer.')
  if(!results.length)throw new Error('No text G-code found. Export a sliced archive, not an unsliced geometry 3MF.')
  return results
}
export async function importSlicerFile(file:File){
  if(file.size>slicerImportLimits.maxInputBytes)throw new Error('Slicer file exceeds the 32 MB import limit.')
  return importSlicerBytes(new Uint8Array(await file.arrayBuffer()),file.name)
}
/** Non-security change detector: metadata edits and prices do not change the slicing job. */
export function printJobFingerprint(doc:ModelDocument){
  const material=doc.printMaterial
  const content=JSON.stringify([doc.id,geometryKey(doc),doc.units,doc.namedParameters,doc.printer,material?{name:material.name,density:material.density}:null,doc.materialPalette,doc.nodes.map(n=>[n.id,n.materialId,n.materialSlot,n.mesh?.triangleMaterials])])
  let hash=2166136261;for(let i=0;i<content.length;i++){hash^=content.charCodeAt(i);hash=Math.imul(hash,16777619)}
  return `print-v1-${content.length.toString(36)}-${(hash>>>0).toString(36)}`
}
export function associateSlicerResult(doc:ModelDocument,result:SlicerCandidate,confirmed:boolean):ModelDocument{
  if(!confirmed)throw new Error('Confirm that this slicer plate belongs to the current geometry, orientation, printer and material.')
  const validated=parseModelDocument({...doc,slicerResult:{...result,association:'user-confirmed',jobFingerprint:printJobFingerprint(doc)},revision:doc.revision+1,updatedAt:new Date().toISOString()})
  return {...doc,slicerResult:validated.slicerResult,revision:validated.revision,updatedAt:validated.updatedAt}
}
export function slicerMaterialCost(doc:ModelDocument):number|null{
  const result=doc.slicerResult,material=doc.printMaterial
  if(!result||result.jobFingerprint!==printJobFingerprint(doc)||result.filamentGrams===undefined||!material?.priceConfigured)return null
  return result.filamentGrams/1000*material.pricePerKg
}
/** Conservative XY bounding-box overlap, including models that bridge an exclusion without vertices inside it. */
export function checkBedExclusions(positions:Float32Array,printer:PrinterProfile){
  if(!positions.length)return []
  let minX=Infinity,minY=Infinity,maxX=-Infinity,maxY=-Infinity
  for(let i=0;i<positions.length;i+=3){minX=Math.min(minX,positions[i]!);maxX=Math.max(maxX,positions[i]!);minY=Math.min(minY,positions[i+1]!);maxY=Math.max(maxY,positions[i+1]!)}
  return (printer.usableBedExclusions??[]).filter(area=>{
    const x=area.x-printer.buildVolume.x/2,y=area.y-printer.buildVolume.y/2
    return minX<x+area.width&&maxX>x&&minY<y+area.depth&&maxY>y
  })
}

