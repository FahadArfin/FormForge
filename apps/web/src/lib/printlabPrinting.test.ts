import {describe, expect, it} from 'vitest'
import {strToU8, zipSync} from 'fflate'
import {createDocument, createNode} from '@formforge/model'
import {parseSlicerText, importSlicerBytes, printJobFingerprint, checkBedExclusions, printerPresets, materialPresets, associateSlicerResult, slicerMaterialCost} from './printlabPrinting'

describe('slicer metadata provenance',()=>{
 it('reads Bambu totals without substituting model-only time or costing',()=>{
  const value=parseSlicerText('; generated by BambuStudio 2.2.1.60\n; model printing time: 10m; total estimated time: 12m 3s\n; total filament weight [g] : 5.25\n; filament cost = 9','part.gcode')
  expect(value).toMatchObject({slicer:'BambuStudio',slicerVersion:'2.2.1.60',durationSeconds:723,filamentGrams:5.25})
  expect(value.durationSource).toContain('total estimated time')
  expect(value).not.toHaveProperty('cost')
 })
 it('reads Orca and Prusa mass lists and normal duration',()=>{
  for(const slicer of ['OrcaSlicer','PrusaSlicer']){
   const result=parseSlicerText(`; generated by ${slicer} 2.9.0\n; filament used [g] = 1.2, 3.4\n; estimated printing time (normal mode) = 1h 2m 3s`,'part.gcode')
   expect(result).toMatchObject({slicer,durationSeconds:3723,filamentGrams:4.6})
  }
 })
 it('keeps missing, malformed, negative, and conflicting values unknown',()=>{
  for(const text of ['G1 X0 Y0','; filament used [g] = -2','; estimated printing time (normal mode) = 9 elephants','; filament used [g] = 2\n; filament used [g] = 3']){
   const result=parseSlicerText(text,'part.gcode'); expect(result.filamentGrams).toBeUndefined();expect(result.durationSeconds).toBeUndefined()
  }
 })
 it('extracts each plate independently from a sliced archive',()=>{
  const data=zipSync({'Metadata/plate_1.gcode':strToU8('; generated by BambuStudio 2.0.0\n; total filament weight [g] : 4'),'Metadata/plate_2.gcode':strToU8('; generated by OrcaSlicer 2.0.0\n; total filament weight [g] : 8'),'3D/3dmodel.model':strToU8('<ignored/>')})
  expect(importSlicerBytes(data,'job.gcode.3mf').map(r=>[r.plate,r.filamentGrams])).toEqual([['Metadata/plate_1.gcode',4],['Metadata/plate_2.gcode',8]])
 })
 it('enforces compressed, entry, expanded and archive-entry limits',()=>{
  const data=zipSync({'a.gcode':strToU8('a'.repeat(2048))})
  expect(()=>importSlicerBytes(data,'job.zip',{maxInputBytes:5})).toThrow(/limit/i)
  expect(()=>importSlicerBytes(data,'job.zip',{maxEntryBytes:1024})).toThrow(/limit/i)
  expect(()=>importSlicerBytes(data,'job.zip',{maxExpandedBytes:1024})).toThrow(/limit/i)
  expect(()=>importSlicerBytes(zipSync({'a.gcode':strToU8('a'),'b.gcode':strToU8('b')}),'job.zip',{maxEntries:1})).toThrow(/limit/i)
 })
 it('rejects binary G-code, unsliced archives and malformed ZIPs',()=>{
  expect(()=>importSlicerBytes(new Uint8Array([66,71,67,79,68,69,0]),'a.gcode')).toThrow(/text/i)
  expect(()=>importSlicerBytes(zipSync({'3D/3dmodel.model':strToU8('<model/>')}),'a.3mf')).toThrow(/sliced/i)
  expect(()=>importSlicerBytes(new Uint8Array([1,2,3]),'a.zip')).toThrow()
 })
})

describe('print-job association',()=>{
 it('requires explicit confirmation and invalidates on geometry, rotation, printer or material changes',()=>{
  const doc={...createDocument(),nodes:[createNode('box')]}, result=parseSlicerText('; total filament weight [g] : 10','a.gcode')
  expect(()=>associateSlicerResult(doc,result,false)).toThrow(/confirm/i)
  const saved=associateSlicerResult(doc,result,true)
  expect(saved.slicerResult?.jobFingerprint).toBe(printJobFingerprint(doc))
  expect(saved.slicerResult?.association).toBe('user-confirmed')
  for(const changed of [{...doc,printer:{...doc.printer,nozzleDiameter:.6}},{...doc,printMaterial:materialPresets.PETG},{...doc,nodes:[{...doc.nodes[0]!,transform:{...doc.nodes[0]!.transform,rotation:{x:90,y:0,z:0}}}]}])expect(printJobFingerprint(changed)).not.toBe(printJobFingerprint(doc))
  expect(printJobFingerprint({...doc,name:'Renamed',revision:123})).toBe(printJobFingerprint(doc))
 })
 it('only costs fresh slicer mass against a user-configured price',()=>{
  const doc=associateSlicerResult({...createDocument(),printMaterial:{...materialPresets.PLA,pricePerKg:20,priceConfigured:true}},parseSlicerText('; total filament weight [g] : 10','a.gcode'),true)
  expect(slicerMaterialCost(doc)).toBe(.2)
  expect(slicerMaterialCost({...doc,printMaterial:{...doc.printMaterial!,priceConfigured:false}})).toBeNull()
  expect(slicerMaterialCost({...doc,printer:{...doc.printer,nozzleDiameter:.8}})).toBeNull()
 })
 it('checks centered world geometry against bed-corner exclusions',()=>{
  expect(checkBedExclusions(new Float32Array([-128,-128,0,-120,-120,10]),printerPresets.P1S)).toHaveLength(1)
  expect(checkBedExclusions(new Float32Array([0,0,0,20,20,10]),printerPresets.P1S)).toHaveLength(0)
 })
})

it('rejects truncated archives even when all local G-code data is present',()=>{
 const data=zipSync({'a.gcode':strToU8('; generated by PrusaSlicer 2.9.0')})
 expect(()=>importSlicerBytes(data.subarray(0,data.length-22),'part.zip')).toThrow(/archive/i)
})
it('enforces actual expansion limits even if the local header lies about size',()=>{
 const data=zipSync({'a.gcode':strToU8('; comment\n'.repeat(5000))})
 new DataView(data.buffer).setUint32(22,1,true)
 expect(()=>importSlicerBytes(data,'part.zip',{maxEntryBytes:1024})).toThrow(/limit/i)
})
it('preserves evaluated geometry references when adding print metadata',()=>{
 const doc={...createDocument(),nodes:[createNode('box')]}
 const next=associateSlicerResult(doc,parseSlicerText('; total filament weight [g] : 10','a.gcode'),true)
 expect(next.nodes).toBe(doc.nodes);expect(next.printer).toBe(doc.printer);expect(next.sculptStrokes).toBe(doc.sculptStrokes)
})
it('uses a reported total once when per-filament values are also present',()=>{
 expect(parseSlicerText('; filament used [g] = 1.2, 3.4\n; total filament used [g] = 4.6','a.gcode').filamentGrams).toBe(4.6)
})
it('keeps a missing slicer version unknown instead of reading the generation date marker',()=>{
 expect(parseSlicerText('; generated by PrusaSlicer on 2026-10-12','a.gcode')).toMatchObject({slicer:'PrusaSlicer'})
 expect(parseSlicerText('; generated by PrusaSlicer on 2026-10-12','a.gcode').slicerVersion).toBeUndefined()
})

