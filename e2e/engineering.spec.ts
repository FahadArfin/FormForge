import {test,expect} from '@playwright/test'
test('engineering shelf clarifies, previews, applies, undoes and recovers locally',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/#studio')
 await page.getByRole('button',{name:'Ask AI',exact:true}).click()
 const phone=(page.viewportSize()?.width??1440)<981
 await page.getByText('Measured rack-shelf designer',{exact:true}).click()
 await page.getByRole('button',{name:'Create shelf plan',exact:true}).click()
 await expect(page.getByRole('button',{name:'Preview proposal',exact:true})).toBeDisabled()
 await expect(page.getByText('What is the device width?',{exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Load illustrative measurements',exact:true}).click()
 await page.getByLabel('Plate thickness',{exact:true}).fill('4')
 await page.getByLabel('Ventilation slot count',{exact:true}).fill('6')
 await page.getByRole('button',{name:'Create shelf plan',exact:true}).click()
 await page.getByRole('button',{name:'Preview proposal',exact:true}).click()
 if(phone)await page.getByRole('button',{name:'Close assistant panel',exact:true}).click()
 await expect(page.getByRole('button',{name:'Apply proposal',exact:true})).toBeVisible()
 await expect(page.getByRole('img',{name:'Engineering proposal geometry',exact:true})).toBeVisible()
 expect(await page.locator('.viewport-wrap').evaluate(el=>el.getBoundingClientRect().height)).toBeGreaterThan(400)
 await page.screenshot({path:phone?'.audit/printlab-phone.png':'.audit/printlab-desktop.png'})
 await page.getByRole('button',{name:'Apply proposal',exact:true}).click()
 await expect(page.locator('.toast')).toContainText('Engineering proposal applied')
 await page.getByRole('button',{name:'Undo',exact:true}).click()
 await page.getByRole('button',{name:'Redo',exact:true}).click()
 await expect(page.getByRole('button',{name:'Saved on this device',exact:true})).toBeVisible()
 await page.reload()
 await page.getByRole('button',{name:'Engineering',exact:true}).click()
 await expect(page.locator('.statusbar')).toContainText('12 features')
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true)
 expect(errors).toEqual([])
})
