import {test,expect} from '@playwright/test'

test('Ask AI opens beside the unchanged studio, preserves drafts, and stays separate from Engineering',async({page})=>{
 await page.goto('/#studio')
 const phone=(page.viewportSize()?.width??1440)<981
 const canvas=page.locator('.viewport-canvas')
 await expect(canvas).toBeVisible()
 await canvas.evaluate(el=>el.setAttribute('data-dock-test','original'))
 await page.getByRole('button',{name:'Engineering',exact:true}).click()
 await expect(page.getByRole('textbox',{name:'Describe your design'})).toBeHidden()
 if(phone)await page.getByRole('button',{name:'Close inspector panel',exact:true}).click()
 const entry=page.getByRole('button',{name:'Ask AI',exact:true})
 await entry.click()
 await expect(entry).toHaveAttribute('aria-expanded','true')
 const chat=page.locator('#assistant-dock'),composer=page.getByRole('textbox',{name:'Describe your design'})
 await expect(composer).toBeVisible()
 await composer.fill('Make a playful pencil holder, 80 mm tall.')
 const box=await chat.boundingBox(),viewport=await page.locator('.viewport-wrap').boundingBox()
 expect(box!.x+box!.width).toBeCloseTo(page.viewportSize()!.width,0)
 if(!phone){expect(viewport!.x+viewport!.width).toBeLessThanOrEqual(box!.x+1);expect(viewport!.width).toBeGreaterThan(350)}
 if(phone)await page.keyboard.press('Escape')
 else await page.getByRole('button',{name:'Close assistant panel'}).click()
 await expect(composer).toBeHidden()
 await expect(entry).toBeFocused()
 await entry.click()
 await expect(composer).toHaveValue('Make a playful pencil holder, 80 mm tall.')
 await expect(canvas).toHaveAttribute('data-dock-test','original')
 await page.screenshot({path:phone?'.audit/assistant-dock-phone.png':'.audit/assistant-dock-desktop.png'})
 await page.getByRole('button',{name:'More creation tools',exact:true}).click()
 await expect(page.getByRole('dialog')).toBeVisible()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true)
})


test('AI dock becomes an accessible drawer when the window narrows',async({page})=>{
 test.skip((page.viewportSize()?.width??1440)<981,'Desktop resize lifecycle')
 await page.goto('/#studio')
 await page.getByRole('button',{name:'Ask AI',exact:true}).click()
 await page.getByRole('button',{name:'Measure',exact:true}).first().click()
 await page.setViewportSize({width:820,height:960})
 await expect(page.getByRole('dialog',{name:'AI engineering assistant'})).toHaveAttribute('aria-modal','true')
 await page.keyboard.press('Escape')
 await expect(page.getByRole('textbox',{name:'Describe your design'})).toBeHidden()
 await page.getByRole('button',{name:'Engineering',exact:true}).click()
 await page.getByRole('button',{name:'Close inspector panel',exact:true}).click()
 const canvas=await page.locator('.viewport-wrap').boundingBox(),workspace=await page.locator('.workspace').boundingBox()
 expect(canvas!.y).toBeCloseTo(workspace!.y,0)
 expect(canvas!.x+canvas!.width).toBeCloseTo(820,0)
 await page.getByRole('button',{name:'Ask AI',exact:true}).click()
 await page.setViewportSize({width:1440,height:960})
 await expect(page.locator('#assistant-dock')).not.toHaveAttribute('aria-modal','true')
 await expect(page.locator('.viewport-wrap')).not.toHaveAttribute('inert','')
})
